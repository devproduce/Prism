  static Uint8List encodeToJpeg(Uint8List bytes, {int quality = 85}) {
    final decoded = image_lib.decodeImage(bytes);
    if (decoded == null) {
      throw const FormatException('Unsupported image format');
    }
    return Uint8List.fromList(
      image_lib.encodeJpg(decoded, quality: quality),
    );
  }

  static Future<Uint8List> readAsJpegBytes(
    File file, {
    int quality = 85,
  }) async {
    final bytes = await file.readAsBytes();
    return encodeToJpeg(bytes, quality: quality);
  }

  static Future<File> saveJpegFile(
    Uint8List bytes,
    File file, {
    int quality = 85,
  }) async {
    final jpeg = encodeToJpeg(bytes, quality: quality);
    await file.writeAsBytes(jpeg);
    return file;
  }
